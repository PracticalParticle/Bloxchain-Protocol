/**
 * Generate a sanity env file aligned to remote_evm.
 *
 * Reads:
 * - deployed-addresses.json (remote_evm.AccountBlox)
 *
 * Usage:
 *   npx tsx scripts/sanity-sdk/generate-remote-evm-env.ts
 *   npx tsx scripts/sanity-sdk/generate-remote-evm-env.ts --out .env.sanity.remote_evm
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const root = path.resolve(__dirname, '../..');

const deployedPath = path.join(root, 'deployed-addresses.json');

